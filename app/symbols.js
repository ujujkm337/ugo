const tri = (x, dir) => {                       // полупроводниковый треугольник
  const tip = dir > 0 ? x + 26 : x - 26;
  return `<path d="M${x} 13 L${x} 47 L${tip} 30 Z"/><line x1="${tip}" y1="12" x2="${tip}" y2="48"/>`;
};
const arrowOut = (x, y) => `<path d="M${x} ${y} L${x + 13} ${y - 11}" /><path d="M${x + 13} ${y - 11} L${x + 6} ${y - 11} M${x + 13} ${y - 11} L${x + 13} ${y - 4}"/>`;
